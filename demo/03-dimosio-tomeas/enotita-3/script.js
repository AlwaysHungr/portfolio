/* =========================================================================
   ΜΗΧΑΝΙΣΜΟΣ ΠΛΟΗΓΗΣΗΣ & RENDERING
   ========================================================================= */
(function () {
  var current = 0;
  var total = SLIDES.length;

  var elSlide = document.getElementById('slide');
  var elNav = document.getElementById('sidebarNav');
  var elCounter = document.getElementById('counter');
  var elCrumb = document.getElementById('crumb');
  var elProgress = document.getElementById('progressFill');
  var elProgressBar = document.querySelector('.progressbar');
  var elSidebarPct = document.getElementById('sidebarProgressText');
  var elDots = document.getElementById('dots');
  var prevBtn = document.getElementById('prevBtn');
  var nextBtn = document.getElementById('nextBtn');
  var app = document.getElementById('app');
  var region = document.getElementById('slide-region');

  function pad(n) { return (n < 10 ? '0' : '') + n; }

  /* ---- Build sidebar (grouped) ---- */
  function buildSidebar() {
    var html = '';
    var lastGroup = null;
    SLIDES.forEach(function (s, i) {
      if (s.group !== lastGroup) {
        if (lastGroup !== null) html += '</div>';
        html += '<div class="nav-group"><div class="nav-group__label">' + s.group + '</div>';
        lastGroup = s.group;
      }
      html += '<button class="nav-item" type="button" data-i="' + i + '" aria-label="Μετάβαση στη διαφάνεια ' + (i + 1) + ': ' + s.nav.replace(/"/g, '') + '">' +
        '<span class="nav-item__num" data-n="' + pad(i + 1) + '"></span>' +
        '<span class="nav-item__txt">' + s.nav + '</span></button>';
    });
    html += '</div>';
    elNav.innerHTML = html;
    elNav.querySelectorAll('.nav-item').forEach(function (btn) {
      btn.addEventListener('click', function () {
        go(parseInt(btn.getAttribute('data-i'), 10));
        if (window.matchMedia('(max-width: 880px)').matches) app.classList.remove('sidebar-open');
      });
    });
  }

  /* ---- Build dots ---- */
  function buildDots() {
    var html = '';
    SLIDES.forEach(function (s, i) {
      html += '<button class="dot' + (s.section ? ' is-section' : '') + '" type="button" data-i="' + i + '" aria-label="Διαφάνεια ' + (i + 1) + '"></button>';
    });
    elDots.innerHTML = html;
    elDots.querySelectorAll('.dot').forEach(function (d) {
      d.addEventListener('click', function () { go(parseInt(d.getAttribute('data-i'), 10)); });
    });
  }

  /* ---- Render current slide ---- */
  function render() {
    var s = SLIDES[current];
    elSlide.innerHTML = s.html;
    elSlide.setAttribute('aria-label', 'Διαφάνεια ' + (current + 1) + ' από ' + total + ': ' + s.nav);
    region.scrollTop = 0;

    elCounter.textContent = pad(current + 1) + ' / ' + pad(total);
    elCrumb.textContent = s.group + '  ·  ' + s.nav;

    var pct = Math.round(((current + 1) / total) * 100);
    elProgress.style.width = pct + '%';
    elProgressBar.setAttribute('aria-valuenow', pct);
    elSidebarPct.textContent = pct + '%';

    prevBtn.disabled = current === 0;
    nextBtn.disabled = current === total - 1;

    // nav active/done state
    elNav.querySelectorAll('.nav-item').forEach(function (btn) {
      var i = parseInt(btn.getAttribute('data-i'), 10);
      btn.classList.toggle('is-active', i === current);
      btn.classList.toggle('is-done', i < current);
      if (i === current) btn.setAttribute('aria-current', 'true'); else btn.removeAttribute('aria-current');
    });
    var active = elNav.querySelector('.nav-item.is-active');
    if (active) active.scrollIntoView({ block: 'nearest' });

    elDots.querySelectorAll('.dot').forEach(function (d) {
      d.classList.toggle('is-active', parseInt(d.getAttribute('data-i'), 10) === current);
    });
  }

  function go(i) {
    if (i < 0 || i >= total || i === current) { if (i === current) return; }
    current = Math.max(0, Math.min(total - 1, i));
    render();
  }
  function next() { if (current < total - 1) go(current + 1); }
  function prev() { if (current > 0) go(current - 1); }

  /* ---- Controls ---- */
  nextBtn.addEventListener('click', next);
  prevBtn.addEventListener('click', prev);

  document.getElementById('toggleSidebar').addEventListener('click', function () {
    if (window.matchMedia('(max-width: 880px)').matches) {
      app.classList.toggle('sidebar-open');
      this.setAttribute('aria-expanded', app.classList.contains('sidebar-open'));
    } else {
      app.classList.toggle('sidebar-collapsed');
      this.setAttribute('aria-expanded', !app.classList.contains('sidebar-collapsed'));
    }
  });

  /* ---- Theme toggle (persist in localStorage) ---- */
  var themeBtn = document.getElementById('toggleTheme');
  try {
    var saved = localStorage.getItem('ai-gov-theme');
    if (saved) document.body.setAttribute('data-theme', saved);
  } catch (e) {}
  function syncThemeBtn() {
    var dark = document.body.getAttribute('data-theme') === 'dark';
    themeBtn.setAttribute('aria-pressed', dark);
  }
  syncThemeBtn();
  themeBtn.addEventListener('click', function () {
    var dark = document.body.getAttribute('data-theme') === 'dark';
    var nv = dark ? 'light' : 'dark';
    document.body.setAttribute('data-theme', nv);
    try { localStorage.setItem('ai-gov-theme', nv); } catch (e) {}
    syncThemeBtn();
  });

  /* ---- Keyboard navigation ---- */
  document.addEventListener('keydown', function (e) {
    var tag = (e.target && e.target.tagName) || '';
    if (tag === 'INPUT' || tag === 'TEXTAREA') return;
    if (e.key === 'ArrowRight' || e.key === 'PageDown') { e.preventDefault(); next(); }
    else if (e.key === 'ArrowLeft' || e.key === 'PageUp') { e.preventDefault(); prev(); }
    else if (e.key === 'Home') { e.preventDefault(); go(0); }
    else if (e.key === 'End') { e.preventDefault(); go(total - 1); }
  });

  /* ---- Interaction delegation on the slide ---- */
  elSlide.addEventListener('click', function (e) {
    // Accordion (κανονιστικά πλαίσια, κριτήρια, στοιχεία τεκμηρίωσης)
    var accH = e.target.closest('.acc-header');
    if (accH) {
      var open = accH.getAttribute('aria-expanded') === 'true';
      accH.setAttribute('aria-expanded', !open);
      var body = accH.nextElementSibling;
      body.style.maxHeight = open ? null : body.scrollHeight + 'px';
      return;
    }
    // Glossary expandable terms
    var gq = e.target.closest('.gloss-q');
    if (gq) {
      var go_ = gq.getAttribute('aria-expanded') === 'true';
      gq.setAttribute('aria-expanded', !go_);
      var ga = gq.nextElementSibling;
      ga.style.maxHeight = go_ ? null : ga.scrollHeight + 'px';
      return;
    }
    // Tabs
    var tb = e.target.closest('.tab-btn');
    if (tb) {
      var list = tb.closest('.tabs');
      list.querySelectorAll('.tab-btn').forEach(function (b) { b.setAttribute('aria-selected', 'false'); });
      tb.setAttribute('aria-selected', 'true');
      var panelId = tb.getAttribute('aria-controls');
      list.querySelectorAll('.tab-panel').forEach(function (p) {
        p.hidden = (p.id !== panelId);
      });
      return;
    }
    // Reveal cards (click-to-reveal έννοιες)
    var rc = e.target.closest('.reveal-card');
    if (rc) {
      var ro = rc.getAttribute('aria-expanded') === 'true';
      rc.setAttribute('aria-expanded', !ro);
      rc.classList.toggle('is-open', !ro);
      return;
    }
    // Interactive checklist
    var ci = e.target.closest('.check-item');
    if (ci) {
      var cc = ci.getAttribute('aria-pressed') === 'true';
      ci.setAttribute('aria-pressed', !cc);
      ci.classList.toggle('is-checked', !cc);
      var wrap = ci.closest('.checklist');
      var statusWrap = wrap.parentElement;
      var checkedCount = wrap.querySelectorAll('.check-item.is-checked').length;
      var out = statusWrap.querySelector('.js-checked');
      if (out) out.textContent = checkedCount;
      return;
    }
  });

  /* ---- Init ---- */
  buildSidebar();
  buildDots();
  render();
})();
