/* ---------- Helpers κατασκευής συστατικών ---------- */
function head(kicker, title, sub) {
  return (kicker ? '<span class="s-kicker">' + kicker + '</span>' : '') +
    '<h2 class="s-title">' + title + '</h2>' +
    (sub ? '<p class="s-sub">' + sub + '</p>' : '');
}
function card(icon, title, text, tag) {
  return '<div class="card">' +
    (tag ? '<span class="card__tag">' + tag + '</span>' : '') +
    '<div class="card__icon">' + icon + '</div>' +
    '<h3 class="card__title">' + title + '</h3>' +
    '<p class="card__text">' + text + '</p></div>';
}
function reveal(term, answer) {
  return '<button class="reveal-card" type="button" aria-expanded="false">' +
    '<span class="reveal-card__q"><span class="reveal-card__plus">' + I.plus + '</span>' +
    '<span class="reveal-card__term">' + term + '</span></span>' +
    '<span class="reveal-card__a">' + answer + '</span>' +
    '<span class="reveal-card__hint">' + I.eye + ' Πατήστε για επεξήγηση</span>' +
    '</button>';
}
function tabs(items) {
  var btns = '', panels = '';
  items.forEach(function (it, i) {
    btns += '<button class="tab-btn" role="tab" type="button" aria-selected="' + (i === 0) + '" ' +
      'id="tab-' + it.id + '" aria-controls="panel-' + it.id + '">' + it.label + '</button>';
    panels += '<div class="tab-panel" role="tabpanel" id="panel-' + it.id + '" aria-labelledby="tab-' + it.id + '"' +
      (i === 0 ? '' : ' hidden') + '>' + it.body + '</div>';
  });
  return '<div class="tabs"><div class="tabs__list" role="tablist">' + btns + '</div>' + panels + '</div>';
}
function accordion(items) {
  var h = '<div class="accordion">';
  items.forEach(function (it, i) {
    h += '<div class="acc-item"><button class="acc-header" type="button" aria-expanded="false">' +
      '<span class="acc-num">' + (i + 1) + '</span>' +
      '<span class="acc-title">' + it.title + '</span>' +
      '<span class="acc-chev">' + I.chev + '</span></button>' +
      '<div class="acc-body"><div class="acc-body__inner">' + it.body + '</div></div></div>';
  });
  return h + '</div>';
}
function timeline(items) {
  var h = '<div class="timeline">';
  items.forEach(function (it, i) {
    h += '<div class="tl-item"><span class="tl-dot">' + (i + 1) + '</span>' +
      '<div class="tl-card"><h4>' + it.title + '</h4><p>' + it.text + '</p></div></div>';
  });
  return h + '</div>';
}
function callout(kind, label, body) {
  var ico = kind === 'danger' ? I.alert : kind === 'warn' ? I.alert : kind === 'ok' ? I.check : I.info;
  return '<div class="callout callout--' + kind + '"><div class="callout__ico">' + ico + '</div>' +
    '<div class="callout__body"><span class="callout__label">' + label + '</span>' + body + '</div></div>';
}
function scenario(badge, title, context, steps, note) {
  var s = steps.map(function (t) {
    return '<div class="scenario__step">' + I.arrow + '<span>' + t + '</span></div>';
  }).join('');
  return '<div class="scenario"><div class="scenario__head">' + I.map +
    '<div><div class="scenario__badge">' + badge + '</div><div class="scenario__title">' + title + '</div></div></div>' +
    '<div class="scenario__body"><p class="scenario__context">' + context + '</p>' +
    '<div class="scenario__steps">' + s + '</div>' +
    (note ? '<div class="scenario__note">' + note + '</div>' : '') + '</div></div>';
}
function reflection(q, hint) {
  return '<div class="reflection"><div class="reflection__label">' + I.think + ' Σκέψου</div>' +
    '<p class="reflection__q">' + q + '</p>' +
    (hint ? '<p class="reflection__hint">' + hint + '</p>' : '') + '</div>';
}
function takeaway(label, points) {
  var li = points.map(function (p) { return '<li>' + I.check + '<span>' + p + '</span></li>'; }).join('');
  return '<div class="takeaway"><div class="takeaway__ico">' + I.star + '</div>' +
    '<div class="takeaway__label">' + label + '</div>' +
    '<ul class="takeaway__list">' + li + '</ul></div>';
}
function checklist(intro, items) {
  var li = items.map(function (it) {
    return '<button class="check-item" type="button" aria-pressed="false">' +
      '<span class="check-box">' + I.check + '</span>' +
      '<span class="check-text"><strong>' + it.t + '</strong>' + it.d + '</span></button>';
  }).join('');
  return (intro ? '<p class="s-lead">' + intro + '</p>' : '') +
    '<div class="checklist" data-total="' + items.length + '">' + li + '</div>' +
    '<div class="checklist__status">' + I.info + ' <span><b class="js-checked">0</b> από ' + items.length + ' σημεία επισημασμένα</span></div>';
}

